/**
 * Digby Code — durable agent-run state (durability Phase 1).
 *
 * The coding agent loop executes IN-PROCESS: a blue-green deploy / restart
 * kills it with the container. This module is the durable seam: every coding
 * run gets an agent_runs row, the loop write-ahead checkpoints its full resume
 * state BEFORE each tool call, and every emitted run event is appended to
 * agent_events so a reconnecting client (Last-Event-ID / ?after_seq=) can
 * replay what it missed — even from the OTHER blue/green color after a flip.
 *
 * Status lifecycle: running → completed | failed | cancelled (terminal;
 * checkpoint nulled) or → interrupted (shutdown/crash; checkpoint RETAINED so a
 * later process can resume). 'queued' exists for the Phase-2 worker-tier claim
 * seam and is unused in Phase 1.
 *
 * live-runs.ts stays dependency-free by design: it never imports this module.
 * The stream controller wires the two together.
 */

