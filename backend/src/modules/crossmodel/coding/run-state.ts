export type AgentRunStatus = 'queued' | 'running' | 'completed' | 'failed' | 'cancelled' | 'interrupted';

/**
 * Write-ahead resume state persisted to agent_runs.checkpoint. Captured at the
 * top of each loop step (preModel) and before each tool call (dispatch).
 * Resume rehydrates the transcript + counters and continues at STEP
 * granularity: a 'dispatch' checkpoint is trimmed back to its step's preModel
 * state on resume (trimToPreModel), so a partially-dispatched turn is
 * REGENERATED by the model rather than re-entered mid-batch. At-least-once per
 * in-flight turn; completed steps are NEVER re-run (their tool results are
 * already in the transcript).
 */
export interface RunCheckpoint {
  version: 1;
  /**
   * Monotonic write fence (audit #8): stamped SYNCHRONOUSLY at each
   * onCheckpoint invocation (run-executor), so invocation order defines seq
   * order even though the writes themselves are async fire-and-forget.
   * writeCheckpoint refuses any write whose seq <= the stored one — an
   * out-of-order late write (slow git snapshot ahead of it) can no longer
   * regress the stored checkpoint to an EARLIER step, which on resume replayed
   * completed steps (double execution). Optional: pre-fence checkpoints lack
   * it and take the legacy unfenced write.
   */
  checkpointSeq?: number;
  /** Full provider transcript as of the checkpoint (system + history + turns). */
  messages: any[];
  /** Current loop step + budget (the budget can grow via goal-continue/auto-verify). */
  step: number;
  stepBudget: number;
  phase: 'preModel' | 'dispatch';
  /** Tool calls not yet executed at a dispatch checkpoint (observability; P2 fine-grained resume). */
  pendingToolCalls?: Array<{ id: string; name: string; arguments: string }>;
  compactionCount: number;
  modelErrored: boolean;
  modelErrorRecoveries: number;
  /** Bounded backoff-and-retry attempts for TRANSIENT provider failures
   *  (429/5xx/network) — tracked separately from modelErrorRecoveries since
   *  2026-08-20 (tickets 039dceb8/1e465443): rate limits need time, not a
   *  smaller/compacted request. Optional: pre-split checkpoints lack it. */
  transientRecoveries?: number;
  repetitionRetries: number;
  leakRetries: number;
  autoContinueRounds: number;
  autoVerifyIters: number;
  lastPlanSig: string;
  lastContinueDiffHash: string;
  continueStalls: number;
  selfAudited: boolean;
  lastToolSig: string;
  repeatCount: number;
  runStartedAt: number;
  deadlineOffsetMs: number;
  recentDiffHashes: string[];
  failureSigCounts: Record<string, number>;
  /** Resume MUST reuse the same usage runId so commitRunUsage stays idempotent. */
  usageRunId: string;
  /**
   * build 2026-10-11 T1 — the ORIGINAL bodies of tool results tier-1 context clearing replaced with stubs
   * (context-gauge.ts tier1Act; newest kept under TIER1_CLEARED_TEXTS_MAX_CHARS). A resumed run's evidence guard
   * unions them into its prior-attempt haystack (run-executor guardPriorToolTexts) — the rehydrated messages carry
   * only the stubs. Optional: absent when nothing was cleared (and on pre-T1 checkpoints).
   */
  clearedToolTexts?: string[];
  /**
   * Durable transcript row the interrupted attempt was streaming into
   * (run-executor persistPartial). A RESUMED attempt seeds its assistantMsgId
   * from here so it UPDATES the same row instead of appending a second
   * assistant row — the duplicate-bubble double-persist (prod chat ddb4acc5:
   * one send left a partial 'P' row from the pre-deploy attempt AND a full
   * 'PONG' row from the resumed one). Optional: pre-fix checkpoints lack it
   * (null/undefined → the resumed attempt appends as before). Stamped by the
   * executor's onCheckpoint wrapper, not the agent loop.
   */
  assistantMsgId?: string | null;
  /**
   * Worktree git snapshot (812767b7): the agent's checked-out branch + a stash
   * commit of uncommitted work, captured at checkpoint time. On resume after a
   * wiped worktree, reattachWorktree rebuilds on this branch and re-applies the
   * wip state instead of rolling back to the session branch with a clean tree.
   */
  worktree?: import('./workspace.service').WorktreeGitSnapshot;
}

/**
 * The assistant transcript row a claimed run should continue writing into:
 * only a RESUME carries one forward (its checkpoint recorded the row the
 * interrupted attempt streamed into — see RunCheckpoint.assistantMsgId);
 * every other claim kind starts fresh. Pure — pinned by
 * run-state.resume-row.test.ts against the duplicate-bubble double-persist.
 */
export function resumeAssistantMsgId(
  kind: string,
  checkpoint: Pick<RunCheckpoint, 'assistantMsgId'> | null | undefined,
): string | null {
  if (kind !== 'resume') return null;
  return checkpoint?.assistantMsgId ?? null;
}

/** How long a 'running' row may go without a heartbeat before a crash is assumed. */
export const RUN_STALE_MS = 10 * 60 * 1000;
/** Lease written alongside every heartbeat/checkpoint — the Phase-2 claim seam. */
export const LEASE_MS = 6 * 60 * 1000;

/** Open the durable row for a run about to execute on this instance. */
export async function createAgentRun(sessionId: string): Promise<string> {
  const now = new Date();
  const row = await prisma.agentRun.create({
    data: {
      sessionId,
      status: 'running',
      startedAt: now,
      heartbeatAt: now,
      leaseExpiresAt: new Date(now.getTime() + LEASE_MS),
    },
  });
  return row.id;
}

/**
 * Write-ahead checkpoint + liveness beat. Fire-and-forget from the agent loop.
 * Guarded on status='running' so a late write can't resurrect a checkpoint onto
 * a row a finalize already closed (write/finalize race on shutdown).
 *
 * Monotonic fence (audit #8): when the checkpoint carries a checkpointSeq, the
 * UPDATE additionally requires stored seq < incoming seq — compared IN the
 * WHERE via a jsonb expression so the check+write is one atomic statement (a
 * cheap SELECT-then-UPDATE would reopen the very race this closes). A stale
 * write (seq <= stored) is silently skipped with a debug log: the newer
 * checkpoint already on the row is the truth, and regressing it made resume
 * replay completed steps (double execution). Checkpoints without a seq
 * (legacy callers/tests) keep the plain status-guarded write.
 */
export async function writeCheckpoint(runId: string, checkpoint: RunCheckpoint): Promise<void> {
  const now = new Date();
  const leaseExpiresAt = new Date(now.getTime() + LEASE_MS);
  const seq = checkpoint.checkpointSeq;
  if (typeof seq === 'number' && Number.isFinite(seq)) {
    const updated = await prisma.$executeRaw`
      UPDATE "agent_runs"
      SET "checkpoint" = ${JSON.stringify(checkpoint)}::jsonb,
          "currentStep" = ${checkpoint.step},
          "heartbeatAt" = ${now},
          "leaseExpiresAt" = ${leaseExpiresAt}
      WHERE "id" = ${runId} AND "status" = 'running'
        AND COALESCE(("checkpoint"->>'checkpointSeq')::bigint, -1) < ${seq}`;
    if (Number(updated) === 0) {
      logger.debug(`writeCheckpoint: skipped stale/out-of-order checkpoint write for run ${runId} (seq ${seq} <= stored seq, or the run is no longer running)`);
    }
    return;
  }
  await prisma.agentRun.updateMany({
    where: { id: runId, status: 'running' },
    data: {
      checkpoint: checkpoint as unknown as object,
      currentStep: checkpoint.step,
      heartbeatAt: now,
      leaseExpiresAt,
    },
  });
}

/** Liveness-only beat (piggybacks on the run-lock refresh interval). */
export async function heartbeatAgentRun(runId: string): Promise<number> {
  const now = new Date();
  // FO firing 46 (chat 5a87b912, 2026-09-29): the count is RETURNED, not
  // discarded — 0 means the durable row is gone (the chat was deleted mid-run
  // and agent_runs cascaded away) or no longer running; either way the
  // executor must stop the zombie (it kept executing ~90 min of tools with
  // every receipt/journal write failing the chat FK, n=97). updateMany never
  // throws P2025, so the count is the ONLY signal a deleted row gives.
  const r = await prisma.agentRun.updateMany({
    where: { id: runId, status: 'running' },
    data: { heartbeatAt: now, leaseExpiresAt: new Date(now.getTime() + LEASE_MS) },
  });
  return r.count;
}

// ── Trimmed TERMINAL checkpoint (agent-decisions prerequisite 6, 2026-09-27) ─
// `agent_runs.checkpoint` was NULL on every terminal run (0/5,927 — replay
// miner §4.2), so the goal-continue counters a run ended with
// (autoContinueRounds / continueStalls / lastPlanSig) were unrecoverable and
// the `goal_continue_worth` decision (design §2.4) could not be replayed.
// A terminal finalize now keeps a TRIMMED summary in the same column: the
// loop counters + the plan step STATES (id:status pairs mined from
// lastPlanSig — never the step text, never the transcript), ≤ 4 KB,
// `terminal: true` and NO `messages`. Every resume reader gates on
// isResumableCheckpoint (a transcript-bearing, non-terminal shape), and the
// claim SQL never selects terminal rows anyway, so a trimmed summary can never
// be resumed. 'interrupted' still RETAINS the full checkpoint. Any read /
// trim failure falls back to the old DbNull. Both this trim and the
// goal_continue loop_metrics row in agent.ts are unconditional.

/** The ≤ 4 KB terminal summary kept in agent_runs.checkpoint on completed | failed | cancelled. */
export interface TerminalCheckpoint {
  version: 1;
  terminal: true;
  status: Exclude<AgentRunStatus, 'queued' | 'running' | 'interrupted'>;
  step: number;
  stepBudget: number;
  autoContinueRounds: number;
  continueStalls: number;
  autoVerifyIters: number;
  compactionCount: number;
  selfAudited: boolean;
  runStartedAt: number;
  deadlineOffsetMs: number;
  /** Plan step STATES at the last goal-continue evaluation ("id:status", from lastPlanSig; text dropped) — the board the decision saw. */
  planSteps: string[];
  /** The plan signature hashed (sha-less djb2 hex) so a replay can pair it with plan_update rows without carrying the text. */
  lastPlanSigHash: string;
}

export const TERMINAL_CHECKPOINT_MAX_CHARS = 4096;

/** A checkpoint a resume may rehydrate from: a transcript-bearing, non-terminal shape. Pure. */
export function isResumableCheckpoint(cp: unknown): cp is RunCheckpoint {
  if (!cp || typeof cp !== 'object') return false;
  const c = cp as { messages?: unknown; terminal?: unknown };
  return Array.isArray(c.messages) && c.terminal !== true;
}

function djb2Hex(s: string): string {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0;
  return (h >>> 0).toString(16);
}

/** Pure: the trimmed terminal summary of a full checkpoint (null for a malformed / already-terminal input). Bounded to TERMINAL_CHECKPOINT_MAX_CHARS. */
export function trimTerminalCheckpoint(cp: unknown, status: TerminalCheckpoint['status']): TerminalCheckpoint | null {
  if (!cp || typeof cp !== 'object') return null;
  const c = cp as Partial<RunCheckpoint> & { terminal?: unknown };
  if (c.terminal === true) return null;
  const num = (v: unknown, d = 0): number => (typeof v === 'number' && Number.isFinite(v) ? v : d);
  const sig = typeof c.lastPlanSig === 'string' ? c.lastPlanSig : '';
  // lastPlanSig is `${id}:${status}:${text}` joined by '|' (agent.ts) — keep id:status only.
  const planSteps = sig
    ? sig.split('|').map((part) => { const m = /^([^:]+):([^:]+):/.exec(part); return m ? `${m[1]}:${m[2]}` : ''; }).filter(Boolean)
    : [];
  const out: TerminalCheckpoint = {
    version: 1,
    terminal: true,
    status,
    step: num(c.step),
    stepBudget: num(c.stepBudget),
    autoContinueRounds: num(c.autoContinueRounds),
    continueStalls: num(c.continueStalls),
    autoVerifyIters: num(c.autoVerifyIters),
    compactionCount: num(c.compactionCount),
    selfAudited: c.selfAudited === true,
    runStartedAt: num(c.runStartedAt),
    deadlineOffsetMs: num(c.deadlineOffsetMs),
    planSteps,
    lastPlanSigHash: djb2Hex(sig),
  };
  // Bound: drop plan steps from the tail until the summary fits.
  while (JSON.stringify(out).length > TERMINAL_CHECKPOINT_MAX_CHARS && out.planSteps.length) out.planSteps.pop();
  return out;
}

/**
 * Close a run. Terminal statuses (completed | failed | cancelled) keep only the
 * TRIMMED terminal summary of the checkpoint (see trimTerminalCheckpoint; NULL
 * when the run never checkpointed, or when the read fails) — nothing to
 * resume. 'interrupted'
 * RETAINS the full checkpoint (shutdown/crash — resumable by a later process).
 */
export async function finalizeAgentRun(runId: string, status: AgentRunStatus, error?: string): Promise<void> {
  let terminalCheckpoint: TerminalCheckpoint | null = null;
  if (status !== 'interrupted') {
    try {
      const row = await prisma.agentRun.findUnique({ where: { id: runId }, select: { checkpoint: true } });
      terminalCheckpoint = trimTerminalCheckpoint(row?.checkpoint ?? null, status as TerminalCheckpoint['status']);
    } catch (err: any) {
      logger.debug(`run-state: terminal checkpoint trim skipped for ${runId} (${err?.message ?? err}) — nulling as before`);
      terminalCheckpoint = null;
    }
  }
  await prisma.agentRun.update({
    where: { id: runId },
    data: {
      status,
      finishedAt: new Date(),
      ...(error ? { error: String(error).slice(0, 2000) } : {}),
      ...(status === 'interrupted' ? {} : { checkpoint: terminalCheckpoint ? (terminalCheckpoint as unknown as object) : Prisma.DbNull }),
    },
  });
}

/**
 * Attempt-neutral finalize for the GRACEFUL-shutdown interrupt (worker SIGTERM
 * on a blue-green deploy): ONE atomic update — status 'interrupted',
 * finishedAt set, checkpoint RETAINED (resumable, same as the generic
 * 'interrupted' finalize) AND the claim-time attempts increment compensated
 * (attempts - 1).
 *
 * Doctrine: a graceful deploy interrupt is NOT an attempt — it mirrors
 * requeueRun's H1 ("lock contention is NOT an attempt", run-claim.ts). The row
 * did nothing wrong: claimNextRun burned one of its ATTEMPTS_CAP attempts on
 * the claim, the deploy then stopped the process mid-run, and without the
 * compensation every deploy would consume one of the 3 attempts — the 4th
 * deploy failed a HEALTHY long-running session with 'attempts exhausted'.
 *
 * Crash-loop protection via ATTEMPTS_CAP is preserved: hard crashes / SIGKILL
 * / stale-lease recovery NEVER take this path (no live finalizer runs for
 * those — the crash-recovery sweeps adopt/reconcile their rows and keep the
 * increment), so a genuinely crash-looping run still exhausts its cap.
 */
export async function finalizeAgentRunShutdownInterrupted(runId: string, error?: string): Promise<void> {
  await prisma.agentRun.update({
    where: { id: runId },
    data: {
      status: 'interrupted',
      finishedAt: new Date(),
      ...(error ? { error: String(error).slice(0, 2000) } : {}),
      attempts: { decrement: 1 },
    },
  });
}

/** Flip an interrupted run back to running for a resume (same row, same usage runId). */
export async function resumeAgentRun(runId: string): Promise<void> {
  const now = new Date();
  await prisma.agentRun.update({
    where: { id: runId },
    data: { status: 'running', finishedAt: null, heartbeatAt: now, leaseExpiresAt: new Date(now.getTime() + LEASE_MS) },
  });
}

/**
 * The latest resumable run for a session (interrupted with a checkpoint), if
 * any. Phase 1's controller resumed it when the user sent the next message
 * ("send a new message to continue"); Phase 2's queueAgentRun adopts its
 * checkpoint onto the new queued row, and the worker claim loop picks up
 * interrupted rows directly.
 */
export async function loadLatestResumableRun(sessionId: string): Promise<{ id: string; checkpoint: RunCheckpoint } | null> {
  const row = await prisma.agentRun.findFirst({
    where: { sessionId, status: 'interrupted', checkpoint: { not: Prisma.DbNull } },
    orderBy: { createdAt: 'desc' },
  });
  if (!row?.checkpoint) return null;
  return { id: row.id, checkpoint: row.checkpoint as unknown as RunCheckpoint };
}

/**
 * Adopt rows stuck 'running' from a dead process (killed inside an unabortable
 * await — a delegate, a container command, a compaction call — before its
 * finalizer could mark them interrupted). Rows WITH a checkpoint become
 * resumable ('interrupted'); rows WITHOUT one died before their first
 * checkpoint and are closed 'failed'. SAFE ONLY under the session's exclusive
 * run-lock — the lock proves no live run exists for this session anywhere.
 * Phase 1 called this at the top of the controller's executeRun; Phase 2's
 * worker tier supersedes it with the claim query (stale-running rows are
 * claimed directly by run-claim.ts). Retained for the Phase-1 tests.
 */
export async function adoptStaleRunningRuns(sessionId: string): Promise<number> {
  const resumable = await prisma.agentRun.updateMany({
    where: { sessionId, status: 'running', checkpoint: { not: Prisma.DbNull } },
    data: { status: 'interrupted' },
  });
  await prisma.agentRun.updateMany({
    where: { sessionId, status: 'running' },
    data: { status: 'failed', error: 'process died before the first checkpoint', finishedAt: new Date() },
  });
  return resumable.count;
}

/**
 * Supersede interrupted runs that were NOT chosen for resume — a newer run
 * (resumed or fresh) makes their checkpoints stale landmines that would
 * otherwise be resumed on top of already-completed work later. Pass the runId
 * being resumed to keep it; null keeps none (a fresh run supersedes all).
 */
export async function supersedeInterruptedRuns(sessionId: string, keepRunId: string | null): Promise<number> {
  const r = await prisma.agentRun.updateMany({
    where: { sessionId, status: 'interrupted', ...(keepRunId ? { id: { not: keepRunId } } : {}) },
    data: { status: 'failed', error: 'superseded by a newer run', finishedAt: new Date(), checkpoint: Prisma.DbNull },
  });
  return r.count;
}

/**
 * Boot-time reconciliation: rows left 'running' by a hard-killed instance (no
 * heartbeat within RUN_STALE_MS / lease expired ⇒ nothing is running them) are
 * marked 'interrupted' so their checkpoints stay resumable instead of rotting.
 */
export async function reconcileOrphanedRuns(staleMs: number = RUN_STALE_MS): Promise<number> {
  const cutoff = new Date(Date.now() - staleMs);
  const r = await prisma.agentRun.updateMany({
    where: {
      status: 'running',
      OR: [
        { leaseExpiresAt: { lt: new Date() } },
        { heartbeatAt: { lt: cutoff } },
        { heartbeatAt: null },
      ],
    },
    data: { status: 'interrupted' },
  });
  if (r.count) logger.warn(`reconcileOrphanedRuns: marked ${r.count} orphaned agent run(s) interrupted`);
  return r.count;
}

/** Append one run event to the durable log (seq comes from the live-run registry). */
export async function appendAgentEvent(runId: string, seq: number, type: string, payload: any): Promise<void> {
  // 22P05 guard (FO firing 20, 2026-09-24): a lone surrogate in the payload
  // (truncated LLM thinking, raw byte splice) makes EVERY append of that event
  // fail with `unsupported Unicode escape sequence` — the durable log grows
  // holes (ticket 3581c8c2 class; run e8975be5 lost 12+ appends in one wave).
  // Strip at the boundary; telemetry only when something was actually dropped.
  const report = { stripped: false, dropped: 0 };
  const safePayload = pgSafeDeep(payload ?? {}, report);
  if (report.stripped) {
    recordLoopMetric({ kind: LOOP_METRIC_KINDS.PG_UNSAFE_STRIPPED, value: report.dropped, unit: 'chars',
      sessionId: runId, meta: { seam: 'agent_event' } });
  }
  await prisma.agentEvent.create({ data: { runId, seq, type, payload: safePayload as unknown as object } });
}

/** Events of a run AFTER `afterSeq`, oldest-first — the SSE replay source. */
export async function getAgentEventsAfter(runId: string, afterSeq: number, limit = 5000): Promise<Array<{ seq: number; type: string; payload: any; createdAt?: Date }>> {
  return prisma.agentEvent.findMany({
    where: { runId, seq: { gt: afterSeq } },
    orderBy: { seq: 'asc' },
    take: limit,
    // createdAt rides along so replay frames carry the event's real wall-clock
    // (createFrameWriter → frame.ts); the client stamps replayed parts with it.
    select: { seq: true, type: true, payload: true, createdAt: true },
  });
}

/** Highest persisted seq for a run — the live registry continues from here on resume. */
export async function getMaxAgentEventSeq(runId: string): Promise<number> {
  const agg = await prisma.agentEvent.aggregate({ where: { runId }, _max: { seq: true } });
  return agg._max.seq ?? 0;
}

/** The session's most recent run that has a durable event log (replay target). */
export async function getLatestEventRunId(sessionId: string): Promise<string | null> {
  const row = await prisma.agentRun.findFirst({
    where: { sessionId, events: { some: {} } },
    orderBy: { createdAt: 'desc' },
    select: { id: true },
  });
  return row?.id ?? null;
}

