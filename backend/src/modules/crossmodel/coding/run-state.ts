/**
 * Queue a run for the Phase-2 worker tier. ONE interactive transaction:
 *  (0) the session-status GATE (Phase-3 review H1): flip the session
 *      ready→running INSIDE the txn. The old shape flipped first and queued
 *      second — two transactions — leaving a window where the session was
 *      'running' with NO row and NO lock: exactly the orphan sweep's delete
 *      shape (a genuinely-busy session could be flipped back to 'ready' →
 *      duplicate run). count !== 1 → throw SessionBusyError so the txn rolls
 *      back (no flip, no row);
 *  (a) lock + read the session's interrupted rows (SELECT ... FOR UPDATE,
 *      latest first) — row locks make the read+transition ATOMIC (H1): a
 *      concurrent claim's own FOR UPDATE SKIP LOCKED skips the rows we hold,
 *      and a row a claim flipped interrupted→running no longer matches our
 *      WHERE once its lock releases (READ COMMITTED re-checks the predicate
 *      after a lock wait) — so a checkpoint is adopted ONLY from a row this
 *      txn actually transitioned. The old findFirst-then-supersede pair raced:
 *      a row claimed between the two statements adopted its checkpoint while
 *      the supersede matched 0 rows → two live rows shared one checkpoint;
 *  (b) supersede exactly those rows (failed / 'superseded by a newer run',
 *      checkpoint → NULL — the same shape as supersedeInterruptedRuns),
 *      guarded on status='interrupted' as belt-and-suspenders;
 *  (c) create the 'queued' row carrying `input`, adopting the LATEST non-null
 *      checkpoint from (a) (the new row resumes the interrupted run's work).
 * Returns the new row id. Leaves exactly ONE claimable row per session.
 */
export async function queueAgentRun(sessionId: string, input: RunInput): Promise<string> {
  return prisma.$transaction(async tx => {
    // (0) the busy-gate, INSIDE the txn: count 0 means the session isn't
    // 'ready' — throw so the whole txn rolls back (no flip, no row).
    const gate = await tx.chatCodingState.updateMany({
      where: { id: sessionId, status: 'ready' },
      data: { status: 'running' },
    });
    if (gate.count !== 1) throw new SessionBusyError(); // rolls the whole txn back
    const interrupted = await tx.$queryRaw<Array<{ id: string; checkpoint: unknown }>>`
      SELECT id, checkpoint FROM "agent_runs"
      WHERE "sessionId" = ${sessionId} AND status = 'interrupted'
      ORDER BY "createdAt" DESC
      FOR UPDATE`;
    if (interrupted.length) {
      await tx.agentRun.updateMany({
        where: { id: { in: interrupted.map(r => r.id) }, status: 'interrupted' },
        data: { status: 'failed', error: 'superseded by a newer run', finishedAt: new Date(), checkpoint: Prisma.DbNull },
      });
    }
    // The rows came back latest-first — the FIRST non-null checkpoint is the
    // newest one this txn transitioned (0 rows → create with no checkpoint).
    const adopt = interrupted.find(r => r.checkpoint != null)?.checkpoint;
    const row = await tx.agentRun.create({
      data: {
        sessionId,
        status: 'queued',
        input: input as unknown as object,
        ...(adopt ? { checkpoint: adopt } : {}),
      },
      select: { id: true },
    });
    return row.id;
  });
}

/** The session's latest claimable/in-flight row (queued or running), if any. */
export async function getActiveRunForSession(sessionId: string): Promise<{ id: string; status: string } | null> {
  const row = await prisma.agentRun.findFirst({
    where: { sessionId, status: { in: ['queued', 'running'] } },
    orderBy: { createdAt: 'desc' },
    select: { id: true, status: true },
  });
  return row ?? null;
}

/** The session's latest row of ANY status (SSE replay uses it). */
export async function getLatestRunForSession(sessionId: string): Promise<{ id: string; status: string } | null> {
  const row = await prisma.agentRun.findFirst({
    where: { sessionId },
    orderBy: { createdAt: 'desc' },
    select: { id: true, status: true },
  });
  return row ?? null;
}

/** Close a run as failed: terminal, checkpoint nulled, error truncated. */
export async function markRunFailed(runId: string, error: string): Promise<void> {
  await prisma.agentRun.update({
    where: { id: runId },
    data: { status: 'failed', finishedAt: new Date(), error: String(error).slice(0, 2000), checkpoint: Prisma.DbNull },
  });
}

/**
 * Overnight forensics (fix 4): compose an attempt-failure CAUSE CHAIN for
 * agent_runs.error. Runs e5c355ee/367514ab died 'attempts exhausted' with NO
 * recorded cause — every attempt-failure path now stashes its terminal error
 * on the row through this helper, APPENDING to what earlier attempts recorded
 * instead of overwriting it (an interrupted run that auto-resumes and dies
 * again keeps its FIRST cause at the head of the chain; truncation drops the
 * tail, never the head). With no prior cause the string is passed through
 * bare, so single-attempt failures keep their existing error text. Pure.
 */
export function appendAttemptCause(existing: string | null | undefined, cause: string, attempt?: number): string {
  const clean = String(cause).replace(/\s+/g, ' ').trim();
  const prior = (existing || '').trim();
  if (!prior) return clean.slice(0, 2000);
  const seg = attempt != null ? `attempt ${attempt}: ${clean.slice(0, 600)}` : clean.slice(0, 600);
  return `${prior} | ${seg}`.slice(0, 2000);
}

/**
 * Record one failed attempt's terminal error onto the run row WITHOUT touching
 * its status — the row stays claimable, and the attempts-exhausted give-up
 * (run-executor) reads the stash so it can finally name WHY. Used by the
 * worker's harness-exception catch (which previously swallowed the cause into
 * a log line) and the executor's cold-retry requeue. Appends, never overwrites.
 */
export async function recordAttemptError(runId: string, cause: string, attempt?: number): Promise<void> {
  const row = await prisma.agentRun.findUnique({ where: { id: runId }, select: { error: true } });
  if (!row) return;
  await prisma.agentRun.update({
    where: { id: runId },
    data: { error: appendAttemptCause(row.error, cause, attempt) },
  });
}

/**
 * Record that the executor persisted the user message (crash-safe idempotent
 * insert): guarded on inputConsumedAt IS NULL so a retried attempt can't
 * double-consume the input.
 */
export async function markInputConsumed(runId: string): Promise<void> {
  await prisma.agentRun.updateMany({
    where: { id: runId, inputConsumedAt: null },
    data: { inputConsumedAt: new Date() },
  });
}

/**
 * Trim a 'dispatch' checkpoint's transcript back to its step's preModel state:
 * strip ONLY the trailing in-flight turn — the LAST assistant message with
 * non-empty tool_calls such that everything after it is tool results — so
 * resume REGENERATES that turn instead of re-entering a dispatch batch mid-way.
 * Completed steps sit EARLIER in the transcript and are never touched (their
 * tool results stay). Only call this for phase==='dispatch' checkpoints: there
 * the trailing assistant-tool_calls message is the in-flight turn by
 * construction. Pure.
 */
export function trimToPreModel(messages: any[]): any[] {
  let idx = -1;
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m?.role === 'tool') continue; // partial results of the in-flight turn
    if (m?.role === 'assistant' && Array.isArray(m?.tool_calls) && m.tool_calls.length) idx = i;
    break; // the first non-tool message from the end decides
  }
  return idx === -1 ? [...messages] : messages.slice(0, idx);
}
