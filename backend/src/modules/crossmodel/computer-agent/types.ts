/**
 * Computer Agent — shared types
 *
 * Digby's computer-use feature: a vision model sees the user's Mac screen and
 * drives it (click, type, key presses, scroll, open apps) through a small action
 * vocabulary. One driver implements it: LocalComputerDriver — the user's paired
 * Mac via the Digby agent (agentVersion ≥ 0.3.0), over the same agentBroker
 * long-poll channel as iMessage and the local browser.
 *
 * Coordinate contract: the model clicks in IMAGE-PIXEL space of the most recent
 * screenshot (which is downscaled for the model); the Mac agent converts to
 * native screen points itself. The loop never does scaling math.
 */

/** The action vocabulary the vision model is given as tools.
 *
 *  W3 (2026-09-25, Windows 0.9.0): two Windows-only members join the union —
 *  'uia_tree' and 'uia_invoke' (UI Automation). They are DISPATCHED but never
 *  offered to the model on macOS (computerToolsForPlatform adds them on the
 *  windows branch only), and the wire methods ride a 0.9.0 dispatch gate — the
 *  macOS agent (0.5.x) can never claim them. */
export type ComputerActionName =
  | 'screenshot'
  | 'click'
  | 'type'
  | 'key'
  | 'scroll'
  | 'open'
  | 'uia_tree'
  | 'uia_invoke'
  | 'wait'
  | 'ask_user'
  | 'done';

export interface ComputerAction {
  name: ComputerActionName;
  /** click — image-pixel coordinates of the LAST screenshot */
  x?: number;
  y?: number;
  button?: 'left' | 'right';
  clicks?: 1 | 2;
  /** type */
  text?: string;
  /** key — named key (return, tab, space, delete, escape, arrows, home/end, pageup/down, f1-f12) */
  key?: string;
  modifiers?: string[];
  /** scroll */
  direction?: 'up' | 'down';
  amount?: number;
  /** open — app name or URL */
  target?: string;
  /** wait (cu-diag fix #3, 2026-09-25) — seconds to pause before the harness
   *  takes a fresh screenshot; clamped to WAIT_MAX_SECONDS (10) in the loop.
   *  Never dispatched to the device — the loop converts it to a screenshot. */
  seconds?: number;
  /** uia_tree (Windows 0.9.0) — 'foreground' (default) | 'desktop' */
  root?: string;
  /** uia_tree — depth bound (server clamps 1..12; default 6) */
  max_depth?: number;
  /** uia_tree — node-count bound (server clamps 1..1000; default 300) */
  max_nodes?: number;
  /** uia_invoke (Windows 0.9.0) — the target element's UIA runtime_id */
  runtime_id?: number[];
  /** uia_invoke — which UIA pattern to apply to the element */
  pattern?: 'invoke' | 'toggle' | 'expand' | 'select' | 'focus' | 'set_value';
  /** ask_user / done — message to the user */
  message?: string;
  /** the model's short rationale for this step (surfaced for transparency) */
  reasoning?: string;
}

export interface ComputerObservation {
  ok: boolean;
  action: ComputerActionName;
  /** base64 JPEG of the current screen (always present after a successful
   *  dispatched action — the driver auto-screenshots after every action) */
  screenshotBase64?: string;
  /** W3 (Windows 0.9.0): uia_tree observations carry the compact linearized
   *  accessibility tree here INSTEAD of a screenshot (the tree IS the
   *  observation — the agent does not send a frame). macOS never sets it. */
  text?: string;
  /** uia_tree — how many nodes the linearized tree carried (bounded by
   *  max_nodes). Present only on uia_tree observations. */
  node_count?: number;
  imageWidth?: number;
  imageHeight?: number;
  screenWidth?: number;
  screenHeight?: number;
  /** Frontmost app / window at capture time (agent ≥ 0.4.1 — grounds the model
   *  in what the user is ALREADY using, e.g. "Google Chrome"). */
  frontmostApp?: string;
  frontmostWindow?: string;
  /** Multi-display capture (Mac agent ≥ 0.6.1, cu-diag 2026-09-25 fix #1):
   *  which display the frame came from (`displayId` = CGDirectDisplayID,
   *  `displayIndex` = the 1-based screencapture index, `displayCount` = active
   *  displays) and which display OWNS the frontmost window (null = unknown).
   *  When frontmostWindowDisplayId ≠ displayId the model's focus is OFF-CAMERA
   *  — the loop says so loudly instead of counting the unchanged frame as dead
   *  input. Older agents omit all of these (undefined = unknown, never a
   *  split). */
  displayId?: number;
  displayIndex?: number;
  displayCount?: number;
  displayName?: string;
  frontmostWindowDisplayId?: number | null;
  pointerDisplayId?: number | null;
  captureReason?: string;
  /** Owner-presence facts (Mac agent ≥ 0.6.1, cu-diag fix #6): seconds since
   *  the last HID input NOT generated by the agent itself (null = unknown),
   *  the raw OS reading, and whether a remote-control session (Screen
   *  Sharing / TeamViewer) looks attached. Older agents omit these. */
  hidIdleSeconds?: number | null;
  hidIdleRawSeconds?: number | null;
  remoteSession?: { active: boolean; kinds?: string[] };
  error?: string;
}

/** Executes the action vocabulary against the paired Mac. */
export interface ComputerDriver {
  execute(action: ComputerAction): Promise<ComputerObservation>;
}

export interface ComputerAgentInput {
  userId: string;
  chatId: string | null;
  message: string;
  /** SSE emitter from the controller — (type, data) => void. */
  sendEvent: (type: string, data: any) => void;
  /** Cap loop steps below the default (tool-delegated sub-sessions run bounded). */
  maxSteps?: number;
  /** Wall-clock budget in ms — past it, tools are dropped so the model must answer. */
  deadlineMs?: number;
  /** Multi-Mac (2026-09-24): target a specific paired Mac by label/name/id.
   *  Omit to use the default Mac (single-Mac users see zero change). */
  device?: string;
  /** Ticket 8fe9429c (2026-09-25) — OBSERVE-ONLY mode for delegated read-only
   *  workers. 'observe' = the vision model may LOOK at the paired screen
   *  (screenshot, uia_tree) but every input action (click, type, key —
   *  including app-quit keystrokes like cmd+q — scroll, open, uia_invoke) is
   *  refused at dispatch and NEVER reaches the device. The live incident: an
   *  observation sub-agent quit Terminal on the harvest Mac, killing a
   *  nohup'd tar+scp transfer. Absent = 'full' (the historical behavior —
   *  the orchestrator/lead runs full computer use). */
  inputMode?: ComputerInputMode;
  /** cu-diag 2026-09-25 fix #6 — owner-presence gate. true = this session was
   *  started by a MACHINE run (supervisor wake, schedule, hook, lane) rather
   *  than a human turn. A machine-triggered session becomes CAMERA-ONLY when
   *  the owner appears to be using the device (recent human HID input, or a
   *  remote-control session attached); an interactive session only gets a
   *  one-line note. Absent = interactive (historical behavior). Kill switch
   *  OWNER_PRESENCE_GATE_DISABLED=1. */
  machineTriggered?: boolean;
  /** cu-diag fix #6 — who is driving: recorded next to the per-device use-lock
   *  so a contending session's busy refusal can NAME the holder (chat id +
   *  lane) instead of "another session". */
  holder?: { chatId?: string | null; lane?: string | null };
}

/** cu-diag fix #6 — the per-device use-lock holder record (use-lock.ts). */
export interface ComputerUseHolder {
  chatId: string | null;
  lane: string | null;
  /** ISO timestamp the holder took the lock. */
  since: string | null;
}

/** Ticket 8fe9429c — the device-input mode of a computer-use session.
 *  'full'    = the historical behavior: the vision model sees the screen AND
 *              drives it (click/type/key/scroll/open).
 *  'observe' = camera-only: screenshots (and uia_tree reads) allowed; every
 *              synthetic-input action is refused at the dispatch gate. */
export type ComputerInputMode = 'full' | 'observe';

export interface ComputerAgentResult {
  finalResponse: string;
  elapsed: number;
  steps: number;
  /** Paired-Mac availability at selection time — surfaced so the caller can
   *  answer "why didn't computer use engage?" (the localBrowserStatus pattern). */
  localStatus?: string;
  /** Present when the session could not run at all (no usable Mac agent) —
   *  a hard, cause-naming notice for the tool-result surface. */
  capabilityNotice?: string;
  /** Multi-Mac: the human name of the Mac that ran (result headers report it). */
  device?: string;
  /** Ticket d427c381 (2026-10-27): true when the device was chosen because the
   *  TASK TEXT named it (the `device` param was omitted). The tool-result
   *  header renders the device line LOUDLY so a caller can never mistake
   *  another Mac's healthy capture for the named machine's. */
  deviceAutoBound?: boolean;
  /** Ticket d427c381: paired-device names the task text mentioned (a
   *  multi-name refusal carries the full list; a success carries the bound
   *  name(s)) — rendered into the header when present. */
  taskTextNamedDevices?: string[];
  /** Ticket d427c381: the task text named a DIFFERENT paired device than the
   *  one driven (explicit `device` param wins over prose) — the header warns
   *  about the mismatch. */
  taskTextNamesOtherThanParam?: string[];
  /** Ticket 8fe9429c — true when this session ran in OBSERVE-ONLY mode
   *  (inputMode 'observe': screenshots allowed, every input action refused at
   *  the dispatch gate). Absent/undefined = a normal full-control session. */
  observeOnly?: boolean;
  /** Ticket c468f922 (2026-10-28): the selected device's PRE-LOGIN INPUT
   *  capability — `status:'unavailable'` because no privileged helper ships,
   *  and `blockedNow:true` when the device reported it is sitting at a
   *  lock/login screen. Present on every result shape that selected a device
   *  (like the device flags) so a calling lane reads a typed fact instead of
   *  inferring one from a loop that landed nothing. */
  prelogin?: {
    status: 'available' | 'unavailable';
    blockedNow: boolean;
    reason: string;
  };
  /** Ticket c468f922 (owner ruling 2026-10-29): BROKERED REMOTE ACCESS for the
   *  selected device — the OS's own remote channel (macOS Screen Sharing /
   *  Windows RDP), hardened tunnel-only per the owner's TeamViewer-shaped
   *  decision. Deliberately SEPARATE from `prelogin` above: `prelogin` answers
   *  "can this run's input land at a login window?" (still NO — no RFB/RDP
   *  client ships), while this answers "is there a hardened operator channel
   *  that reaches the login window?". A lane must read both, never treat one
   *  as the other — conflating them is the c468f922 bug class. */
  remoteAccess?: {
    /** c468f922 (owner ruling 2026-10-30): the TYPED health state — the
     *  owner's "off / on / unavailable" (plus `blocked`). This is the field a
     *  scheduler must branch on. `ready` alone is NOT enough: `off` and
     *  `unavailable` are both `ready:false`, and they mean opposite things —
     *  `off` is the healthy default (do nothing), `unavailable` is "nobody
     *  reported, do not assume" (don't dispatch blind). Declaring it here
     *  keeps this contract in lockstep with RemoteAccessVerdict, which is what
     *  driver.ts actually returns; omitting it made the typed state
     *  undeclared at exactly the consumer that needs it. */
    state: 'off' | 'on' | 'blocked' | 'unavailable';
    enabled: boolean;
    tunnelOnly: boolean;
    ready: boolean;
    reason: string;
  };
  /** cu-diag fix #6 — present when the session was refused because another
   *  session holds the device (a STRUCTURED non-error: the caller reports who
   *  is driving and retries later). `holder` fields are null when the holder
   *  recorded nothing (legacy holder / Redis hiccup). */
  busy?: {
    holderChatId: string | null;
    holderLane: string | null;
    since: string | null;
    /** How long this contender waited for the lock before giving up (ms). */
    waitedMs: number;
  };
  /** cu-diag fix #6 — the owner-presence verdict at session start (and, for a
   *  machine run, whether the gate turned the session camera-only). */
  ownerPresence?: {
    active: boolean;
    reason: string;
    /** true = a machine-triggered session was switched to observe-only by the gate. */
    gated: boolean;
  };
  /** cu-diag fix #3 (2026-09-25): harness-measured counters for the session —
   *  stamped into the tool-result header so lanes and supervisors reason from
   *  harness FACTS, not the sub-agent's narration. Absent when the session
   *  never started (capability-gate paths). */
  harness?: ComputerHarnessCounters;
}

/** cu-diag fix #3 — what the harness itself measured during a session. */
export interface ComputerHarnessCounters {
  /** Repeated-action nudges issued (the model's identical action refused). */
  refusedRepeats: number;
  /** Write-path watchdog strikes scored (consecutive-no-change input actions). */
  noChangeStrikes: number;
  /** Frames graded unreadable (solid / contentless captures). */
  degenerateFrames: number;
  /** Last captured frame geometry, "WxH" in image pixels ("" when none). */
  frameGeometry: string;
  /** Displays the agent reported (fix #1 forwards it; null when not stamped). */
  displayCount: number | null;
  /** Harness positive-control probes run / passed (fix #2). */
  probesRun: number;
  probesPassed: number;
  /** True once a probe proved input lands on this device this session. */
  inputProven: boolean;
  /** Frontmost-app changes observed on byte-identical frames (positive input evidence). */
  frontmostChanges: number;
}
